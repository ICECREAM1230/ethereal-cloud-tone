#include <stdint.h>
#include "control_service.h"
#include "control_latency.h"
#define COLS 40u
#define CHARS 800u
static cs_service_t controls;
static cl_state_t latency;
static char screen[CHARS];
static inline uint32_t rd(unsigned off) {
    uint32_t v=*(volatile uint32_t *)(uintptr_t)(0xf8000000u+off);
    __asm__ volatile("fence iorw,iorw" ::: "memory");return v;
}
static inline void wr(unsigned off,uint32_t v) {
    *(volatile uint32_t *)(uintptr_t)(0xf8000000u+off)=v;
    __asm__ volatile("fence iorw,iorw" ::: "memory");
}
static void put(unsigned row,unsigned col,const char *s) {
    while(*s && row<20u && col<COLS)screen[row*COLS+col++]=*s++;
}
static void number(unsigned row,unsigned col,uint32_t v) {
    char tmp[10];unsigned n=0;
    do {tmp[n++]=(char)('0'+v%10u);v/=10u;}while(v && n<10u);
    while(n && col<COLS)screen[row*COLS+col++]=tmp[--n];
}
static const char *engine(unsigned e) {return e==0 ? "SUB" : e==1 ? "KS" : "FM";}
static void render(unsigned requested,uint32_t heartbeat) {
    const cs_stats_t *s=cs_get_stats(&controls);
    for(unsigned i=0;i<CHARS;i++)screen[i]=' ';
    put(1,3,"AE350 MIDI CONTROL LAB");
    put(3,3,"> ENGINE");put(3,16,engine(requested));
    put(4,3,"APPLIED");put(4,16,s->mode<3 ? engine(s->mode) : "WAIT");
    put(5,3,"STATE");put(5,16,s->state==CS_RUNNING ? "RUNNING" :
        s->state==CS_WAIT_READY ? "WAIT BACKEND" : s->state==CS_SWITCHING ? "SWITCHING" :
        s->state==CS_FLUSHING ? "SOURCE FLUSH" : "FAULT");
    put(7,3,"MIDI BYTES");number(7,20,s->raw_bytes);
    put(8,3,"MIDI EVENTS");number(8,20,s->events);
    put(9,3,"COMMAND / ACK");number(9,20,s->commands);number(9,30,s->command_acks);
    put(10,3,"IDLE / STALE");number(10,20,s->idle);number(10,30,s->idle_stale);
    put(11,3,"FLUSH DONE");number(11,20,s->flush_complete);
    put(12,3,"FAULT");number(12,20,s->fault);number(12,30,s->backend_fault);
    put(13,3,"VOICES SUB / KS / FM");
    for(unsigned e=0;e<3;e++) {
        unsigned active=0;
        for(unsigned v=0;v<controls.runtime.manager[e].voice_count;v++)
            if(controls.runtime.manager[e].voices[v].state!=VM_IDLE)active++;
        number(14,5+10*e,active);
    }
    put(15,3,"CPU");number(15,8,heartbeat);
    put(17,3,"KEY0/1 NEXT  KEY2 PREVIOUS");
    put(18,3,"USB HOST + ESP32 RAW MIDI");
    put(19,3,"PCM GENERATED BY FPGA");
}
int main(void) {
    uint32_t keys[3],seq=0,last_draw=0,heartbeat=0;
    unsigned requested=0,draw=CHARS,first=1,fault_marked=0;
    wr(0x1c,0xae350010u);
    if(rd(0)!=0x4d454e55u || rd(4)!=0x10000u) {
        wr(0x1c,0xae3500e1u);for(;;){}
    }
    wr(0x1c,0xae350011u);
    for(unsigned k=0;k<3;k++)keys[k]=rd(0x10+4*k);
    (void)cs_init(&controls,0,7,0,rd(8));
    cl_init(&latency,0);
    for(;;) {
        uint32_t now=rd(8);
        unsigned work=cs_poll(&controls,now,&cs_default_budget);
        for(unsigned k=0;k<3;k++) {
            uint32_t count=rd(0x10+4*k),delta=count-keys[k];keys[k]=count;
            if(delta>32)delta=32;
            while(delta--)requested=(requested+(k==2 ? 2u : 1u))%3u;
        }
        if(requested!=controls.stats.requested_mode)
            (void)cs_request_mode(&controls,(uint8_t)requested);
        if(controls.stats.fault && !fault_marked) {
            wr(0x1c,0xae3500e1u);fault_marked=1;
        }
        /* Snapshot reads are bounded; formatting/TX only get a slice after
         * current MIDI, command ACK, template and route work has drained. */
        cl_poll(&latency,!work && cs_diagnostics_idle(&controls),now);
        if(draw==CHARS && (uint32_t)(now-last_draw)>=100u && !(rd(0xc)&1u)) {
            render(requested,++heartbeat);draw=0;last_draw=now;
        }
        if(draw<CHARS) {
            // Forty character writes per service slice. MIDI/ACK polling runs
            // between every row instead of waiting for a complete 800-word frame.
            unsigned end=draw+COLS;
            while(draw<end) {wr(0x1000+4*draw,(uint8_t)screen[draw]);draw++;}
            if(draw==CHARS) {
                seq=seq==0xffffffffu ? 1u : seq+1u;
                if(first && !fault_marked)wr(0x1c,0xae350020u);
                wr(0x50,seq);
                if(first && !fault_marked)wr(0x1c,0xae350021u);
                first=0;
            }
        }
    }
}
